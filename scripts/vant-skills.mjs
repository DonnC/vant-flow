import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skill = 'projects/vant-flow/skills/vant-flow';
const version = JSON.parse(fs.readFileSync(path.join(root, 'projects/vant-flow/package.json'))).version;
const files = new Map();
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const sources = [
  'src/lib/models/document.model.ts', 'src/lib/config.ts', 'src/lib/link-href.ts',
  'src/lib/utils/script-editor-support.ts', 'src/lib/services/form-context.ts',
  'src/lib/components/form-renderer/form-renderer.component.ts',
  'src/lib/components/builder/builder-container.component.ts',
  'src/public-api.ts', 'baobab/src/public-api.ts',
  'baobab/src/lib/field-config.ts', 'baobab/src/lib/script-namespace.ts', 'baobab/src/lib/link-href.ts'
].map(file => `projects/vant-flow/${file}`);
let contract = `# Generated Vant Flow ${version} contracts\n\nGenerated by npm run skills:generate. Do not edit this snapshot.\n\n`;
for (const file of sources) {
  const source = ts.createSourceFile(file, read(file), ts.ScriptTarget.Latest, true);
  const snippets = [];
  for (const node of source.statements) {
    if (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node) || ts.isExportDeclaration(node)) {
      snippets.push(node.getText(source));
    } else if (ts.isFunctionDeclaration(node) && node.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword)) {
      snippets.push(node.getText(source).slice(0, node.body ? node.body.getStart(source) - node.getStart(source) : undefined).trimEnd() + ';');
    } else if (ts.isClassDeclaration(node)) {
      const members = node.members.filter(member => !member.modifiers?.some(m => [ts.SyntaxKind.PrivateKeyword, ts.SyntaxKind.ProtectedKeyword].includes(m.kind)) && !ts.isConstructorDeclaration(member));
      snippets.push(`// ${node.name?.text}: public members (implementation omitted)\n` + members.map(member => {
        const end = member.body ? member.body.getStart(source) : member.end;
        return source.text.slice(member.getStart(source), end).trimEnd() + (member.body ? ';' : '');
      }).join('\n'));
    } else if (ts.isVariableStatement(node) && /VF_FRM_METHOD_COMPLETIONS|DECLARATIONS|VF_BAOBAB/.test(node.getText(source))) {
      snippets.push(node.getText(source));
    }
  }
  contract += `## ${file}\n\n\`\`\`typescript\n${snippets.join('\n\n')}\n\`\`\`\n\n`;
}
files.set(`${skill}/references/contracts.md`, contract);
for (const name of fs.readdirSync(path.join(root, 'data/docs')).filter(name => name.endsWith('.md'))) {
  files.set(`${skill}/references/docs/${name}`, read(`data/docs/${name}`));
}
for (const name of fs.readdirSync(path.join(root, 'data/examples')).filter(name => name.endsWith('.json'))) {
  const data = read(`data/examples/${name}`);
  JSON.parse(data);
  files.set(`${skill}/examples/schemas/${name}`, data);
}
files.set(`${skill}/references/release.json`, JSON.stringify({ skillVersion: '1.0.0', libraryVersion: version, sources }, null, 2) + '\n');
const mode = process.argv[2];
if (!['generate', 'check'].includes(mode)) throw new Error('Usage: node scripts/vant-skills.mjs generate|check');
const stale = [];
for (const [file, contents] of files) {
  if (mode === 'generate') {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.writeFileSync(path.join(root, file), contents);
  } else if (!fs.existsSync(path.join(root, file)) || read(file) !== contents) stale.push(file);
}
const entry = read(`${skill}/SKILL.md`);
if (!entry.includes(`vant-flow-version: ${version}`)) throw new Error('Update the skill supported library version.');
for (const file of ['SKILL.md', 'references/integration.md', 'references/runtime.md', 'references/maintenance.md']) {
  const content = read(`${skill}/${file}`);
  for (const match of content.matchAll(/\]\(([^)]+)\)/g)) {
    if (!/^(https?:|#)/.test(match[1]) && !fs.existsSync(path.resolve(root, skill, path.dirname(file), match[1]))) {
      throw new Error(`Broken skill reference in ${file}: ${match[1]}`);
    }
  }
}
if (stale.length) throw new Error(`Stale skill snapshots; run npm run skills:generate:\n${stale.join('\n')}`);
console.log(`${mode}: ${files.size} skill snapshots verified for Vant Flow ${version}`);
